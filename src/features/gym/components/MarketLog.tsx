import { DEFAULT_MARKET_PRESETS } from '@/types/gym'

// ── Types ────────────────────────────────────────────────────────────────────

interface GroceryItem {
  id: string
  name: string
  price: number
  quantity: number
  store: string
  category: string
}

interface WeeklyMarketLog {
  weekStart: string
  items: GroceryItem[]
}

// ── Helpers ──────────────────────────────────────────────────────────────────

const STORES = ['D1', 'Carulla', 'Exito', 'Rappi', 'Other']
const CATEGORIES = ['Protein', 'Carbs', 'Snacks', 'Dairy', 'Produce', 'Hygiene', 'Other']

const fmtCOP = (n: number) => {
  if (Math.abs(n) >= 1_000_000) return `$${(n / 1_000_000).toFixed(1)}M`
  if (Math.abs(n) >= 1_000) return `$${Math.round(n / 1_000)}K`
  return `$${n}`
}
const fmtFull = (n: number) => `$${n.toLocaleString('es-CO')}`

/** Spend split for the selected week, as bars relative to the week total. */
function SpendBreakdown({ title, rows, total, delay }: { title: string; rows: [string, number][]; total: number; delay: number }) {
  return (
    <WidgetCard title={title} compact delay={delay}>
      <div className="space-y-2">
        {rows.map(([name, amount]) => (
          <div key={name} className="flex items-center justify-between text-xs">
            <span className="text-foreground">{name}</span>
            <div className="flex items-center gap-2">
              <div className="h-1 w-24 rounded-full bg-muted/60">
                <div className="h-full rounded-full bg-foreground/40" style={{ width: `${(amount / total) * 100}%` }} />
              </div>
              <span className="w-14 text-right font-mono tabular-nums text-muted-foreground">{fmtCOP(amount)}</span>
            </div>
          </div>
        ))}
      </div>
    </WidgetCard>
  )
}

// ── Component ────────────────────────────────────────────────────────────────

export function MarketLog() {
  const reduceMotion = useReducedMotion()
  const today = localDate()
  const todayWeekStart = getWeekDates(today)[0]

  // Current view state
  const [viewYear, setViewYear] = useState(() => Number(today.slice(0, 4)))
  const [viewMonth, setViewMonth] = useState(() => Number(today.slice(5, 7)) - 1)
  const [selectedWeek, setSelectedWeek] = useState(todayWeekStart)

  const monthWeeks = useMemo(() => weeksInMonth(viewYear, viewMonth), [viewYear, viewMonth])

  // Data for selected week
  const [log, setLogState] = useState<WeeklyMarketLog>({ weekStart: selectedWeek, items: [] })
  const [budget, setBudget] = useStore<number>('cortex-market-budget', 646000)
  // The Finances Food budget is the single source of truth; Market spend rolls up into it.
  const [finances, setFinances] = useStore<FinanceDataLike>('cortex-finances', { year: Number(today.slice(0, 4)), items: [] })
  const backfillRan = useRef(false)

  // Suggested shopping list (generated by an MCP tool from previous buys)
  const [marketList, setMarketList] = useStore<MarketList | null>('cortex-market-list', null)

  // All weeks' data for monthly totals
  const [monthLogs, setMonthLogs] = useState<WeeklyMarketLog[]>([])

  // Load selected week
  useEffect(() => {
    readStore<WeeklyMarketLog>(`cortex-market-${selectedWeek}`, { weekStart: selectedWeek, items: [] })
      .then(setLogState)
  }, [selectedWeek])

  // Load all weeks in month for monthly total
  useEffect(() => {
    Promise.all(
      monthWeeks.map(w => readStore<WeeklyMarketLog>(`cortex-market-${w}`, { weekStart: w, items: [] }))
    ).then(setMonthLogs)
  }, [monthWeeks, log]) // re-fetch when current log changes

  // Live sync: the Finances Food "spent" for the viewed month = the month's market total.
  useEffect(() => {
    if (viewYear !== finances.year) return
    const total = sumMarket(monthLogs)
    if (Math.round(foodSpentPrimary(finances, viewMonth)) !== Math.round(total)) {
      setFinances(prev => withFoodSpent(prev, viewMonth, total))
    }
  }, [monthLogs, viewMonth, viewYear, finances, setFinances])

  // One-time backfill: reconcile every month of the finance year from existing market data.
  useEffect(() => {
    if (backfillRan.current || finances.items.length === 0) return
    backfillRan.current = true
    const year = finances.year
    ;(async () => {
      const done = await readStore<boolean>('cortex-food-sync-v1', false)
      if (done) return
      const totals: number[] = []
      for (let m = 0; m < 12; m++) {
        const weeks = weeksInMonth(year, m)
        const logs = await Promise.all(weeks.map(w => readStore<WeeklyMarketLog>(`cortex-market-${w}`, { weekStart: w, items: [] })))
        totals[m] = sumMarket(logs)
      }
      setFinances(prev => {
        let next = prev
        for (let m = 0; m < 12; m++) next = withFoodSpent(next, m, totals[m])
        return next
      })
      writeStore('cortex-food-sync-v1', true)
    })()
  }, [finances, setFinances])

  const setLog = useCallback((fn: (prev: WeeklyMarketLog) => WeeklyMarketLog) => {
    setLogState(prev => {
      const next = fn(prev)
      writeStore(`cortex-market-${selectedWeek}`, next)
      return next
    })
  }, [selectedWeek])

  const [newName, setNewName] = useState('')
  const [newPrice, setNewPrice] = useState('')
  const [newQty, setNewQty] = useState('1')
  const [newStore, setNewStore] = useState('D1')
  const [newCategory, setNewCategory] = useState('Protein')

  // Quick-add presets
  const [presets, setPresets] = useStore<MarketPreset[]>('cortex-market-presets', DEFAULT_MARKET_PRESETS)
  const [newPresetName, setNewPresetName] = useState('')
  const [newPresetPrice, setNewPresetPrice] = useState('')
  const [newPresetStore, setNewPresetStore] = useState('D1')
  const [newPresetCategory, setNewPresetCategory] = useState('Protein')

  const weeklyTotal = useMemo(() => marketItemsTotal(log.items), [log.items])
  const monthlyTotal = useMemo(() => sumMarket(monthLogs), [monthLogs])
  // Budget shown = the Finances Food budget for this month (falls back to the legacy market budget).
  const foodBudget = foodBudgetForMonth(finances, viewMonth) || budget
  const byStore = useMemo(() => spendBy(log.items, item => item.store), [log.items])
  const byCategory = useMemo(() => spendBy(log.items, item => item.category), [log.items])

  const addItem = () => {
    if (!newName.trim() || !newPrice) return
    const item: GroceryItem = {
      id: Date.now().toString(),
      name: newName.trim(),
      price: Number(newPrice) || 0,
      quantity: Number(newQty) || 1,
      store: newStore,
      category: newCategory,
    }
    setLog(prev => ({ ...prev, items: [...prev.items, item] }))
    setNewName('')
    setNewPrice('')
    setNewQty('1')
  }

  const removeItem = (id: string) => {
    setLog(prev => ({ ...prev, items: prev.items.filter(i => i.id !== id) }))
  }

  const quickAddItem = (preset: MarketPreset, addedAt: number) => {
    const item = {
      id: addedAt.toString(),
      name: preset.name,
      price: preset.price,
      quantity: preset.quantity,
      store: preset.store,
      category: preset.category,
    }
    setLog(prev => ({ ...prev, items: [...prev.items, item] }))
  }

  // ── Shopping list ─────────────────────────────────────────────────────────────
  const toggleListItem = (index: number) => {
    setMarketList(prev => prev
      ? { ...prev, items: prev.items.map((it, i) => i === index ? { ...it, checked: !it.checked } : it) }
      : prev)
  }

  const addListItemToWeek = (index: number) => {
    const li = marketList?.items[index]
    if (!li) return
    const item: GroceryItem = {
      id: 'grc-' + Date.now() + '-' + index,
      name: li.name,
      price: li.price,
      quantity: li.quantity,
      store: li.store,
      category: li.category,
    }
    setLog(prev => ({ ...prev, items: [...prev.items, item] }))
    setMarketList(prev => prev
      ? { ...prev, items: prev.items.map((it, i) => i === index ? { ...it, checked: true } : it) }
      : prev)
  }

  const clearMarketList = () => {
    setMarketList(prev => prev ? { ...prev, items: [] } : null)
  }

  const removePreset = (index: number) => {
    setPresets(prev => prev.filter((_, i) => i !== index))
  }

  const saveToPresets = () => {
    if (!newPresetName.trim() || !newPresetPrice) return
    setPresets(prev => [...prev, {
      name: newPresetName.trim(),
      price: Number(newPresetPrice),
      quantity: 1,
      store: newPresetStore,
      category: newPresetCategory,
    }])
    setNewPresetName('')
    setNewPresetPrice('')
  }

  const prevMonth = () => {
    if (viewMonth === 0) { setViewMonth(11); setViewYear(y => y - 1) }
    else setViewMonth(m => m - 1)
  }
  const nextMonth = () => {
    if (viewMonth === 11) { setViewMonth(0); setViewYear(y => y + 1) }
    else setViewMonth(m => m + 1)
  }

  return (
    <div className="mt-4 space-y-4">
      {/* Month + Week navigation */}
      <motion.div initial={reduceMotion ? false : { opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0 }}>
        {/* Month selector */}
        <DateStepper label={`${MONTHS[viewMonth]} ${viewYear}`} previousLabel="Previous month" nextLabel="Next month"
          onPrevious={prevMonth} onNext={nextMonth} className="mb-3 justify-between" />

        {/* Week tabs */}
        <div className="flex gap-1.5 overflow-x-auto pb-1">
          {monthWeeks.map((w, i) => {
            const weekTotal = marketItemsTotal(monthLogs.find(ml => ml.weekStart === w)?.items ?? [])
            return (
              <SelectionCard
                key={w}
                title={`Week ${i + 1}`}
                selected={selectedWeek === w}
                current={w === todayWeekStart}
                onSelect={() => setSelectedWeek(w)}
                className="shrink-0"
              >
                <span>{marketWeekLabel(w)}</span>
                {weekTotal > 0 && <span>{fmtCOP(weekTotal)}</span>}
              </SelectionCard>
            )
          })}
        </div>
      </motion.div>

      {/* Summary tiles */}
      <div className="grid grid-cols-2 gap-3 md:grid-cols-4">
        <StatTile label="Items this week" value={log.items.length} icon={<ShoppingCart />} />
        <StatTile label="Week total" value={fmtCOP(weeklyTotal)} icon={<Store />} />
        <StatTile label="Month total" value={fmtCOP(monthlyTotal)} icon={<TrendingUp />} />
        <div
          className="surface rounded-xl p-4"
          title="Synced with the Finances Food budget"
        >
          <p className="font-mono text-2xs uppercase tracking-wider text-muted-foreground">Food budget</p>
          <InlineNumberEditor
            key={viewMonth}
            value={foodBudget}
            rule={{ min: 0, integer: true }}
            label="Food budget (COP)"
            onCommit={value => {
              if (value === undefined) return
              setFinances(prev => withFoodBudget(prev, viewMonth, value))
              setBudget(() => value || 646000)
            }}
            className="mt-1.5 justify-start font-mono text-2xl font-medium leading-none tabular-nums text-foreground"
            inputClassName="mt-1.5 w-full font-mono text-2xl font-medium tabular-nums"
          >
            {fmtCOP(foodBudget)}
          </InlineNumberEditor>
          <p className={`mt-1.5 font-mono text-2xs tabular-nums ${monthlyTotal <= foodBudget ? 'text-success' : 'text-destructive'}`}>
            {monthlyTotal <= foodBudget ? `${fmtCOP(foodBudget - monthlyTotal)} left` : `Over by ${fmtCOP(monthlyTotal - foodBudget)}`}
          </p>
        </div>
      </div>

      {/* Suggested shopping list (populated by an MCP tool) */}
      <WidgetCard title="Shopping List" compact delay={0.03}>
        {!marketList || marketList.items.length === 0 ? (
          <EmptyState
            message="No list yet."
            hint="Ask Claude to build one from your previous buys."
            className="py-4"
          />
        ) : (
          <div className="space-y-2">
            <div className="flex items-center justify-between">
              <span className="font-mono text-2xs tabular-nums text-foreground-faint">
                {marketList.generatedAt ? `Generated ${relativeMarketDate(marketList.generatedAt, today)}` : ''}
                {typeof marketList.weeksAnalyzed === 'number' ? ` · ${marketList.weeksAnalyzed}w analyzed` : ''}
              </span>
              <Button
                variant="ghost"
                size="xs"
                onClick={clearMarketList}
                className="text-foreground-faint hover:text-destructive"
              >
                Clear
              </Button>
            </div>
            {marketList.items.map((li, i) => (
              <div
                key={`${li.name}-${i}`}
                className="flex items-center justify-between gap-2 border-t border-border/60 pt-2 text-xs first:border-t-0 first:pt-0"
              >
                <label className="flex min-h-11 min-w-0 flex-1 cursor-pointer items-center gap-2 sm:min-h-7">
                  <Checkbox
                    checked={!!li.checked}
                    onChange={() => toggleListItem(i)}
                    aria-label={`Bought ${li.name}`}
                  />
                  <span className={`truncate ${li.checked ? 'text-foreground-faint line-through' : 'text-foreground'}`}>
                    {li.name}
                  </span>
                  <span className="shrink-0 font-mono tabular-nums text-foreground-faint">{li.quantity} · {fmtFull(li.price)}</span>
                </label>
                <div className="flex shrink-0 items-center gap-2">
                  <Chip size="sm" className="hidden sm:inline-flex">{li.store}</Chip>
                  <Chip size="sm" className="hidden sm:inline-flex">{li.category}</Chip>
                  {typeof li.timesBought === 'number' && li.timesBought > 0 && (
                    <span className="font-mono text-2xs tabular-nums text-foreground-faint">{li.timesBought}x</span>
                  )}
                  <Button
                    variant="secondary"
                    size="icon-sm"
                    onClick={() => addListItemToWeek(i)}
                    aria-label={`Add ${li.name} to this week`}
                  >
                    <Plus />
                  </Button>
                </div>
              </div>
            ))}
          </div>
        )}
      </WidgetCard>

      <QuickAddPanel
        title="Quick add"
        editLabel="Edit presets"
        doneLabel="Done editing presets"
        items={presets.map((preset, i) => ({
          key: `${preset.name}-${i}`,
          label: preset.name,
          detail: fmtCOP(preset.price),
          onAdd: () => quickAddItem(preset, Date.now()),
          onRemove: () => removePreset(i),
          removeLabel: `Remove preset ${preset.name}`,
        }))}
      >
        {/* Custom preset form */}
        <div className="flex flex-wrap items-end gap-2">
          <Input placeholder="Name" aria-label="Preset name" value={newPresetName} onChange={(e) => setNewPresetName(e.target.value)}
            className="h-8 min-w-[120px] flex-1 text-xs" />
          <Input type="number" placeholder="Price" aria-label="Preset price (COP)" value={newPresetPrice} onChange={(e) => setNewPresetPrice(e.target.value)}
            className="h-8 w-20 text-xs" />
          <Select value={newPresetStore} onChange={(e) => setNewPresetStore(e.target.value)} aria-label="Preset store"
            className="w-auto h-8 px-2 text-xs">
            {STORES.map(s => <option key={s} value={s}>{s}</option>)}
          </Select>
          <Select value={newPresetCategory} onChange={(e) => setNewPresetCategory(e.target.value)} aria-label="Preset category"
            className="w-auto h-8 px-2 text-xs">
            {CATEGORIES.map(c => <option key={c} value={c}>{c}</option>)}
          </Select>
          <Button variant="secondary" size="icon" onClick={saveToPresets} aria-label="Save preset">
            <Bookmark />
          </Button>
        </div>
      </QuickAddPanel>

      {/* Add item form — only for current or future weeks */}
      <WidgetCard title={`Add Purchase — ${marketWeekLabel(selectedWeek)}`} compact delay={0.05}>
        <div className="flex flex-wrap items-end gap-2">
          <Field label="Item" className="min-w-[120px] flex-1">
            {(id) => <Input id={id} placeholder="Pollo, leche..." value={newName} onChange={(e) => setNewName(e.target.value)} className="h-8 text-xs" onKeyDown={(e) => e.key === 'Enter' && addItem()} />}
          </Field>
          <Field label="Price (COP)" className="w-20">
            {(id) => <Input id={id} type="number" placeholder="12000" value={newPrice} onChange={(e) => setNewPrice(e.target.value)} className="h-8 text-xs" onKeyDown={(e) => e.key === 'Enter' && addItem()} />}
          </Field>
          <Field label="Qty" className="w-14">
            {(id) => <Input id={id} type="number" value={newQty} onChange={(e) => setNewQty(e.target.value)} className="h-8 text-xs" min={1} />}
          </Field>
          <Field label="Store" className="w-20">
            {(id) => (
              <Select id={id} value={newStore} onChange={(e) => setNewStore(e.target.value)} className="h-8 w-full px-2 text-xs">
                {STORES.map(s => <option key={s} value={s}>{s}</option>)}
              </Select>
            )}
          </Field>
          <Field label="Category" className="w-20">
            {(id) => (
              <Select id={id} value={newCategory} onChange={(e) => setNewCategory(e.target.value)} className="h-8 w-full px-2 text-xs">
                {CATEGORIES.map(c => <option key={c} value={c}>{c}</option>)}
              </Select>
            )}
          </Field>
          <Button variant="secondary" size="sm" className="h-8 shrink-0" onClick={addItem} aria-label="Add purchase">
            <Plus />
          </Button>
        </div>
      </WidgetCard>

      {/* Items list */}
      {log.items.length > 0 ? (
        <WidgetCard title={`Purchases — ${marketWeekLabel(selectedWeek)}`} compact delay={0.1}>
          <div className="overflow-x-auto">
            <table className="w-full text-xs">
              <thead>
                <tr className="font-mono text-2xs uppercase tracking-wider text-muted-foreground">
                  <th className="pb-2 text-left font-medium">Item</th>
                  <th className="w-16 pb-2 text-left font-medium">Store</th>
                  <th className="w-16 pb-2 text-left font-medium">Category</th>
                  <th className="w-16 pb-2 text-right font-medium">Price</th>
                  <th className="w-10 pb-2 text-right font-medium">Qty</th>
                  <th className="w-16 pb-2 text-right font-medium">Total</th>
                  <th className="w-8 pb-2"></th>
                </tr>
              </thead>
              <tbody>
                {log.items.map((item) => (
                  <tr key={item.id} className="group border-t border-border/60">
                    <td className="py-1.5 text-foreground">{item.name}</td>
                    <td className="py-1.5 text-muted-foreground">{item.store}</td>
                    <td className="py-1.5 text-muted-foreground">{item.category}</td>
                    <td className="py-1.5 text-right font-mono tabular-nums text-muted-foreground">{fmtFull(item.price)}</td>
                    <td className="py-1.5 text-right font-mono tabular-nums text-muted-foreground">{item.quantity}</td>
                    <td className="py-1.5 text-right font-mono font-medium tabular-nums text-foreground">{fmtFull(item.price * item.quantity)}</td>
                    <td className="py-1.5 text-right">
                      <Button
                        variant="ghost"
                        size="icon-xs"
                        onClick={() => removeItem(item.id)}
                        aria-label={`Remove ${item.name}`}
                        className="text-muted-foreground opacity-0 hover:text-destructive focus-visible:opacity-100 group-hover:opacity-100"
                      >
                        <Trash2 />
                      </Button>
                    </td>
                  </tr>
                ))}
                <tr className="border-t border-border/50 font-medium">
                  <td colSpan={5} className="py-2 text-muted-foreground">Total</td>
                  <td className="py-2 text-right font-mono tabular-nums">{fmtFull(weeklyTotal)}</td>
                  <td></td>
                </tr>
              </tbody>
            </table>
          </div>
        </WidgetCard>
      ) : (
        <EmptyState message="No purchases logged for this week." />
      )}

      {/* Breakdown */}
      {log.items.length > 0 && (
        <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
          <SpendBreakdown title="By Store" rows={byStore} total={weeklyTotal} delay={0.15} />
          <SpendBreakdown title="By Category" rows={byCategory} total={weeklyTotal} delay={0.2} />
        </div>
      )}
    </div>
  )
}
